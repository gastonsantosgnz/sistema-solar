/* Posición geocéntrica de la Luna en km, marco eclíptico J2000.
   out = [x, y, z]. Devuelve también { lon, lat, r } de la fecha.  */
function lunaGeo(jd, out){
  const T = (jd - J2000) / 36525;
  const rev = x => { x = x % 360; return x < 0 ? x + 360 : x; };

  const Lp = rev(218.3164477 + 481267.88123421*T - 0.0015786*T*T + T*T*T/538841 - T*T*T*T/65194000);
  const D  = rev(297.8501921 + 445267.1114034*T - 0.0018819*T*T + T*T*T/545868 - T*T*T*T/113065000);
  const M  = rev(357.5291092 + 35999.0502909*T - 0.0001536*T*T + T*T*T/24490000);
  const Mp = rev(134.9633964 + 477198.8675055*T + 0.0087414*T*T + T*T*T/69699 - T*T*T*T/14712000);
  const F  = rev(93.2720950 + 483202.0175233*T - 0.0036539*T*T - T*T*T/3526000 + T*T*T*T/863310000);
  const A1 = rev(119.75 + 131.849*T);
  const A2 = rev(53.09 + 479264.290*T);
  const A3 = rev(313.45 + 481266.484*T);
  const E  = 1 - 0.002516*T - 0.0000074*T*T;
  const E2 = E * E;

  let sl = 0, sr = 0, sb = 0;
  for (const [d, m, mp, f, l, r] of LUNA_LR){
    const arg = (d*D + m*M + mp*Mp + f*F) * DEG;
    const k = m === 0 ? 1 : (m === 1 || m === -1 ? E : E2);
    sl += l * k * Math.sin(arg);
    sr += r * k * Math.cos(arg);
  }
  sl += 3958*Math.sin(A1*DEG) + 1962*Math.sin((Lp - F)*DEG) + 318*Math.sin(A2*DEG);
  for (const [d, m, mp, f, b] of LUNA_B){
    const arg = (d*D + m*M + mp*Mp + f*F) * DEG;
    const k = m === 0 ? 1 : (m === 1 || m === -1 ? E : E2);
    sb += b * k * Math.sin(arg);
  }
  sb += -2235*Math.sin(Lp*DEG) + 382*Math.sin(A3*DEG)
      + 175*Math.sin((A1 - F)*DEG) + 175*Math.sin((A1 + F)*DEG)
      + 127*Math.sin((Lp - Mp)*DEG) - 115*Math.sin((Lp + Mp)*DEG);

  const lon = Lp + sl/1e6;              // eclíptica de la fecha
  const lat = sb/1e6;
  const r = 385000.56 + sr/1000;        // km

  // precesión de la fecha a J2000 (p_A ≈ 5029.0966″ por siglo)
  const lonJ2000 = (lon - 1.3969713*T) * DEG;
  const latR = lat * DEG;
  if (out){
    const cb = Math.cos(latR);
    out[0] = r * cb * Math.cos(lonJ2000);
    out[1] = r * cb * Math.sin(lonJ2000);
    out[2] = r * Math.sin(latR);
  }
  return { lon, lat, r };
}
